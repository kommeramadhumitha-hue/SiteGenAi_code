export async function downloadProjectAsZip(project: WebsiteProject): Promise<void> {
  const files = generateProjectFiles(project);
  const zip = new JSZip();

  // Root files
  zip.file('index.html', files['index.html']);
  zip.file('README.md', files['README.md']);

  // Assets folder
  const cssFolder = zip.folder('css');
  if (cssFolder) cssFolder.file('styles.css', files['styles.css']);

  const jsFolder = zip.folder('js');
  if (jsFolder) jsFolder.file('main.js', files['script.js']);

  const reactFolder = zip.folder('react-src');
  if (reactFolder) reactFolder.file('App.tsx', files['App.tsx']);

  // Generate ZIP blob
  const content = await zip.generateAsync({ type: 'blob' });
  const filename = `${project.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}-sitegen.zip`;

  // Trigger download
  const link = document.createElement('a');
  link.href = URL.createObjectURL(content);
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(link.href);
}

export function downloadSingleFile(filename: string, content: string, mimeType: string = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
